  await gm.waitForFunction(id=>game.messages.some(message=>message.getFlag('star-wars-ffg','actorUuid')===`Actor.${id}`&&message.isRoll),id);
  check('Owned player skill builds and rolls a native narrative pool; the GM receives the same authenticated actor roll');
  await gm.evaluate(()=>{ui.sidebar.activateTab('chat');ui.sidebar.expand();});
  const initial=await gm.evaluate(id=>game.actors.get(id).system.wounds.value,id);
  const resolveEffect=async(kind,amount)=>{
    await gm.evaluate(id=>{void game.system.api.tabletop.resolve(game.actors.get(id));},id);
    await gm.locator('dialog [name="kind"]').selectOption(kind);await gm.locator('dialog [name="amount"]').fill(String(amount));
    await gm.locator('dialog [name="note"]').fill('Synthetic Alpha acceptance GM ruling.');
    await gm.getByRole('button',{name:'Review change',exact:true}).click();
    await gm.getByRole('button',{name:'Apply reviewed changes',exact:true}).click();
  };
  const soak=await gm.evaluate(id=>game.actors.get(id).system.soak,id);
  await resolveEffect('damage',soak+4);await gm.waitForFunction(({id,value})=>game.actors.get(id).system.wounds.value===value,{id,value:initial+4});
  await player.waitForFunction(({id,value})=>game.actors.get(id).system.wounds.value===value,{id,value:initial+4});
  await gm.evaluate(id=>{void game.system.api.tabletop.history(game.actors.get(id));},id);
  await gm.locator('dialog [data-undo]').first().click();await gm.waitForFunction(({id,value})=>game.actors.get(id).system.wounds.value===value,{id,value:initial});
  await gm.locator('dialog').getByRole('button',{name:'Close',exact:true}).click();
