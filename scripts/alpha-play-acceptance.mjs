  await gm.locator('dialog [name="downtime"]').fill('Alpha fixture: rest and repair.');await gm.getByRole('button',{name:'Preview awards',exact:true}).click();
  await gm.getByRole('button',{name:'Award reviewed changes',exact:true}).click();
  await player.waitForFunction(({id,xp})=>game.actors.get(id).system.xp.available===xp,{id,xp:created.xp+10});
  check('GM previews and commits session XP/credits with a downtime record; the owner receives the synchronized award');
  await player.evaluate(id=>{const actor=game.actors.get(id);actor.sheet.activeTab='skills';void actor.sheet.render({force:true});},id);
