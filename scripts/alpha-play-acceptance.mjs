  const created=await player.evaluate(id=>{const actor=game.actors.get(id);return {species:actor.system.species,career:actor.system.career,brawn:actor.system.characteristics.brawn,xp:actor.system.xp.available,items:actor.items.map(item=>item.type),credits:actor.system.credits};},id);
  assert.equal(created.species,'Human');assert.equal(created.career,'Explorer');assert.equal(created.brawn,3);assert.ok(created.items.includes('armor'));assert.ok(created.credits>=450);
  check('Player completes manual Human/Explorer/Scout creation, free skills, starting XP, equipment, pocket money and Ready for play through native dialogs');
  await sheet.locator('[data-tab="skills"]').click();await sheet.locator('[data-action="skill"][data-skill="athletics"]').click();
