  const beforeReload=await player.evaluate(id=>{const actor=game.actors.get(id);return {phase:actor.system.phase,xp:actor.system.xp,credits:actor.system.credits,wounds:actor.system.wounds,advancement:actor.system.advancement,history:actor.getFlag('star-wars-ffg','workflowHistory')};},id);
  await player.screenshot({path:join(output,'09-alpha-play.png')});await player.reload({waitUntil:"domcontentloaded",timeout:60000});await player.waitForFunction(()=>game.ready);
  assert.deepEqual(await player.evaluate(id=>{const actor=game.actors.get(id);return {phase:actor.system.phase,xp:actor.system.xp,credits:actor.system.credits,wounds:actor.system.wounds,advancement:actor.system.advancement,history:actor.getFlag('star-wars-ffg','workflowHistory')};},id),beforeReload);
