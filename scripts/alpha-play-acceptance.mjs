  await player.waitForFunction(id=>!game.actors.get(id).system.creation.pocketMoneyPending,id);
  // Human species has verified starting skills and no unresolved automatic source exceptions.
  const issues=await player.evaluate(async id=>(await import('/systems/star-wars-ffg/src/creation-guide.mjs')).creationReadiness(game.actors.get(id).system),id);
